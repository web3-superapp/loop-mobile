#!/usr/bin/env python3
"""Regenerate lib/integrations/communication/stream_chat_localizations_en.dart.

Usage: python3 scripts/l10n/gen_stream_english.py [path/to/stream_chat_flutter]

Reads the SDK's abstract `Translations` and writes a `StreamChatLocalizations`
whose every member forwards to `DefaultTranslations.instance` (decision 0281).
Run it after a stream_chat_flutter upgrade; analyze tells you when it is due.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "lib/integrations/communication/stream_chat_localizations_en.dart"


def sdk_dir() -> Path:
    lock = (ROOT / "pubspec.lock").read_text(encoding="utf-8")
    m = re.search(r"\n  stream_chat_flutter:\n(?:    .*\n)*?    version: \"([^\"]+)\"", lock)
    version = m.group(1) if m else "10.3.0"
    return Path.home() / ".pub-cache/hosted/pub.dev" / f"stream_chat_flutter-{version}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("sdk", nargs="?", type=Path)
    args = parser.parse_args()
    source = ((args.sdk or sdk_dir()) / "lib/src/localization/translations.dart").read_text(encoding="utf-8")
    start = source.index("abstract class Translations {")
    end = source.index("\n}\n", start)
    body = "\n".join(
        line for line in source[start + len("abstract class Translations {") : end].splitlines()
        if not line.strip().startswith("///")
    )
    decls = [re.sub(r"\s+", " ", d).strip() for d in body.split(";")]
    members = []
    for d in (d for d in decls if d):
        m = re.match(r"^(.+?) get (\w+)$", d)
        if m:
            members.append(f"  @override\n  {m.group(1)} get {m.group(2)} => _english.{m.group(2)};\n")
            continue
        m = re.match(r"^(.+?) (\w+)\((.*)\)$", d)
        if not m:
            print(f"cannot parse: {d}", file=sys.stderr)
            return 1
        ret, name, params = m.groups()
        call: list[str] = []
        named = re.search(r"\{(.*)\}", params)
        optional = re.search(r"\[(.*)\]", params)
        positional = re.sub(r"[\{\[].*$", "", params)
        call += [a.split()[-1] for a in (x.strip() for x in positional.split(",")) if a]
        if optional:
            call += [a.split("=")[0].split()[-1] for a in (x.strip() for x in optional.group(1).split(",")) if a]
        if named:
            for a in (x.strip() for x in named.group(1).split(",")):
                if a:
                    n = a.split("=")[0].split()[-1]
                    call.append(f"{n}: {n}")
        members.append(f"  @override\n  {ret} {name}({params}) =>\n      _english.{name}({', '.join(call)});\n")
    OUT.write_text(
        "// GENERATED by scripts/l10n/gen_stream_english.py — do not edit by hand.\n"
        "//\n"
        "// Decision 0281: in English the official Stream widgets print the SDK's own\n"
        "// copy. `Localizations` asks every delegate for the app's locale, so LOOP's\n"
        "// Stream delegate answers English with this class: every member forwards to\n"
        "// the SDK's `DefaultTranslations`, nothing is reworded.\n"
        "import 'package:stream_chat_flutter/stream_chat_flutter.dart';\n\n"
        "/// Stream's own English, as a [StreamChatLocalizations].\n"
        "class LoopStreamChatEnglishLocalizations implements StreamChatLocalizations {\n"
        "  const LoopStreamChatEnglishLocalizations();\n\n"
        "  static const DefaultTranslations _english = DefaultTranslations.instance;\n\n"
        + "\n".join(members)
        + "}\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(members)} members")
    return 0


if __name__ == "__main__":
    sys.exit(main())
